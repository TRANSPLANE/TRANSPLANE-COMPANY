export function phrase(
  key: keyof typeof zhTemplates,
  ...values: unknown[]
): string {
  const chunks = getLocale() === "en" ? enTemplates[key] : zhTemplates[key];
  return chunks.reduce(
    (text, chunk, index) =>
      text + chunk + (index < values.length ? String(values[index] ?? "") : ""),
    "",
  );
}

